export function getPreset(id: string): ThemePreset {
  return PRESETS.find((p) => p.id === id) ?? PRESETS[0];
}

/** The same style in the other mode: Night Gold ↔ Day Gold. */
export function presetFor(family: ThemePreset["family"], isDark: boolean): ThemePreset {
  return PRESETS.find((p) => p.family === family && p.isDark === isDark) ?? PRESETS.find((p) => p.isDark === isDark)!;
}

export function getAccent(preset: ThemePreset, accentId: string): AccentSwatch {
  return (
    preset.accentSwatches.find((s) => s.id === accentId) ??
    preset.accentSwatches.find((s) => s.id === preset.defaultAccentId) ??
    preset.accentSwatches[0]
  );
}
