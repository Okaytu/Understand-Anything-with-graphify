CODE_CAP = 20000          # characters of source per file embedded in prompts
# files whose code is never embedded: secret-looking names ...
SKIP_CODE = re.compile(
    r"(^|/)\.env|\.(pem|key|p12|pfx|jks|keystore|kdbx)$|secret|credential"
    r"|(^|/)(id_rsa|id_dsa|id_ecdsa|id_ed25519)(\.|$)|(^|/)\.(netrc|npmrc|pypirc|htpasswd)$",
    re.I,
)
# ... and any file whose text holds a credential-shaped string. Copied from graphify's
# security.py (_SECRET_SHAPE_RE): this script runs under `python3 -I`, so it can't import it.
SECRET_SHAPE = re.compile(
    r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----"
    r"|\b(?:AKIA|ASIA)[0-9A-Z]{16}\b"
    r"|\bgh[pousr]_[A-Za-z0-9]{36,}"
    r"|\bgithub_pat_[A-Za-z0-9_]{22,}"
    r"|\bxox[baprs]-[A-Za-z0-9-]{10,}"
    r"|\b[sr]k_(?:live|test)_[A-Za-z0-9]{10,}"
    r"|\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{20,}"
    r"|\bAIza[0-9A-Za-z_-]{35}\b"
    r"|\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"
    r"|(?<=\bBearer )[A-Za-z0-9._~+/=-]{16,}"
    r"|(?<=://)[^\s/:@]+:[^\s/@]+(?=@)"
)


def load(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def is_file_node(node: dict) -> bool:
    """The dot that stands for a whole file (same rule as graphify_to_ua._is_file_node).
    graphify labels a file by its name, or by part of its path when the name repeats
    ("login/page.tsx", "x/index.ts", "pkg/__init__.py")."""
    source_file = node.get("source_file") or ""
    label = str(node.get("label", ""))
    if not source_file or node.get("_callable"):
        return False
    if label == source_file.rsplit("/", 1)[-1]:
        return True
    return "/" in label and (source_file == label or source_file.endswith("/" + label))


def build_payload(root: Path, html: str) -> dict:
    root = root.resolve()
    # same data folder rule as enrich.py and the dashboard: the legacy folder wins when present
    data_dir = root / ".understand-anything" if (root / ".understand-anything").is_dir() else root / ".ua"
    enr = load(data_dir / "enrichments.json", {})
    files = {p: {"s": v.get("summary", ""), "t": v.get("tags", [])}
             for p, v in (enr.get("files") or {}).items()}
    why = {k: v.get("why", "") for k, v in (enr.get("connections") or {}).items()}
    symbols = {k: {"s": v.get("summary", "")} for k, v in (enr.get("symbols") or {}).items()}
    project = enr.get("project") or {}
    # No agent explanations (a learn-from-zero wiki, or a project not explained yet): fall
    # back to what the dashboard's own graph already says about each file and the project.
    graph = load(data_dir / "knowledge-graph.json", {})
    if not isinstance(graph, dict):
        graph = {}
    gnodes = [n for n in graph.get("nodes", []) if isinstance(n, dict)]
    used_fallback = not files
    if not files:
        for n in gnodes:
            fp, summary = n.get("filePath"), n.get("summary")
            if fp and summary and n.get("type") in {"file", "document", "article", "config"} and not n.get("lineRange"):
                files.setdefault(fp, {"s": summary, "t": (n.get("tags") or [])[:6]})
    if not project and graph:
        path_of = {n.get("id"): n.get("filePath") for n in gnodes}
        overview = (graph.get("project") or {}).get("description", "")
        project = {
            # drop the converter's own "Generated by graphify ..." paragraph
            "description": "\n\n".join(p for p in overview.split("\n\n") if not p.startswith("Generated by graphify")),
            "layers": graph.get("layers", []),
            "tour": [{"title": t.get("title", ""), "description": t.get("description", ""),
                      "files": [path_of[i] for i in t.get("nodeIds", []) if path_of.get(i)]}
                     for t in graph.get("tour", []) if isinstance(t, dict)],
        }
    m = re.search(r"const RAW_NODES = (\[.*?\]);\n", html, re.S)
    nodes = json.loads(m.group(1)) if m else []
    code = {}
    # graph.html's nodes lack graphify's type fields; graph.json has them (outside libraries
    # such as a dynamically imported "jspdf" are "module" nodes there, not files)
    full = load(root / "graphify-out" / "graph.json", {})
    full_by_id = {n.get("id"): n for n in (full.get("nodes", []) if isinstance(full, dict) else []) if isinstance(n, dict)}

    def outside(n: dict) -> bool:
        f = full_by_id.get(n.get("id"), {})
        return bool(f.get("external")) or f.get("type") in {"external", "module"} or bool(f.get("_callable"))

    file_ids: dict[str, str] = {}
    for n in nodes:
        sf = n.get("source_file")
        if is_file_node(n) and not outside(n) and sf not in file_ids:
            file_ids[sf] = n.get("id")
    # The dashboard's graph can name files relative to a sub-folder (learn-from-zero keeps its
    # notes in wiki/, graphify says "wiki/Note.md"): match each fallback path to graphify's.
    sources = {n.get("source_file") for n in nodes if n.get("source_file")}

    def to_source(path: str) -> str:
        if path in sources:
            return path
        hits = [s for s in sources if s.endswith("/" + path)]
        return hits[0] if len(hits) == 1 else path

    if used_fallback:
        files = {to_source(p): v for p, v in files.items()}
        for t in project.get("tour", []) if isinstance(project, dict) else []:
            if isinstance(t, dict) and isinstance(t.get("files"), list):
                t["files"] = [to_source(f) for f in t["files"]]
    for sf in sorted({n.get("source_file") for n in nodes if n.get("source_file")}):
        try:
            # graph.html may come from someone else's repository: only ever read files that
            # really sit inside this project (no "../", absolute paths or links pointing out)
            p = (root / sf).resolve()
            if not p.is_relative_to(root) or not p.is_file() or p.stat().st_size > 400_000:
                continue
            if SKIP_CODE.search(sf) or SKIP_CODE.search(p.relative_to(root).as_posix()):
                continue
            text = p.read_text(encoding="utf-8")
        except (OSError, RuntimeError, UnicodeDecodeError, ValueError):
            continue
        if SECRET_SHAPE.search(text):
            continue
        # an explanation written before the file last changed is marked, not shown as current
        entry = (enr.get("files") or {}).get(sf) or {}
        if entry.get("hash") and sf in files and entry["hash"] != hashlib.sha1(p.read_bytes()).hexdigest()[:16]:
            files[sf] = {**files[sf], "s": files[sf]["s"] + " (Written before this file last changed.)"}
        code[sf] = text[:CODE_CAP] + ("\n… (file continues; cut here to keep the prompt short)" if len(text) > CODE_CAP else "")
    return {
        "name": root.name,
        "overview": project.get("description", ""),
        "groups": [{"name": l.get("name", ""), "description": l.get("description", "")}
                   for l in project.get("layers", [])],
        "tour": [{"title": t.get("title", ""), "description": t.get("description", ""),
                  "files": t.get("files", [])} for t in project.get("tour", [])],
        "files": files, "why": why, "symbols": symbols, "code": code, "fileIds": file_ids,
    }


def safe_json(obj) -> str:
    # "<" as \u003c: embedded source code can then never close the script tag or open an
    # HTML comment ("<!--" + "<script" would change how the browser reads the script)
    s = json.dumps(obj, ensure_ascii=True, separators=(",", ":"))
    return s.replace("<", "\\u003c")


