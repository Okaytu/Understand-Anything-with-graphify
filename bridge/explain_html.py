#!/usr/bin/env python3
"""Add a plain-language layer to graphify's graph.html.

    python3 bridge/explain_html.py <project-dir>

What it adds (everything runs in the browser, no AI, no internet beyond graph.html's own):
  * click a dot  -> a side panel: what it is in plain words, how it connects (with the
                    reason for each link) and a ready-to-copy prompt for ChatGPT / Claude
  * "Impact"     -> highlights everything that depends on the dot, with a count
  * hover a dot  -> its plain-language summary
  * "Health"     -> files nothing uses, circular dependencies, riskiest hub files
  * "Ask"        -> type a question, get the files that match, plus a copyable prompt
  * "Whole project" -> a prompt that explains the entire project

It reads <project>/.ua/enrichments.json (written by bridge/enrich.py) when present; without it
the panel still works from the graph alone. Safe to run again: it replaces its own block.
"""
