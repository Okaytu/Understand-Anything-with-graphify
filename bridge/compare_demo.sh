#!/usr/bin/env bash
# Reproduce notes/comparison-report.md: compare the sample graph that /understand
# built for Understand-Anything itself (committed in the dashboard's public/ folder)
# with what graphify + the bridge build from the exact same commit.
#
#   bridge/compare_demo.sh [output.md]
#
# Needs: git, uv, Node >= 22, pnpm >= 10 (same as bridge/run.sh).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
OUT="${1:-$REPO_ROOT/notes/comparison-report.md}"
UA_GRAPH="$REPO_ROOT/understand-anything/understand-anything-plugin/packages/dashboard/public/knowledge-graph.json"

COMMIT="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["project"]["gitCommitHash"])' "$UA_GRAPH")"
git -C "$REPO_ROOT" cat-file -e "$COMMIT^{commit}" 2>/dev/null || {
  echo "commit $COMMIT (from the /understand graph) is not in this repo's history" >&2; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
SRC="$WORK/understand-anything-$(git -C "$REPO_ROOT" rev-parse --short "$COMMIT")"
mkdir -p "$SRC"
echo "==> extracting Understand-Anything @ $COMMIT"
git -C "$REPO_ROOT" archive "$COMMIT" | tar -x -C "$SRC"

echo "==> graphify + bridge on the same source"
"$REPO_ROOT/bridge/run.sh" "$SRC" --view none

echo "==> comparing"
python3 "$REPO_ROOT/bridge/compare_graphs.py" "$UA_GRAPH" "$SRC/.ua/knowledge-graph.json" \
  --labels understand graphify --project "$SRC" --out "$OUT.tmp"
{
  echo "<!-- Generated by bridge/compare_demo.sh; do not edit by hand. -->"
  echo
  # Paths under the temporary checkout are not meaningful once it is deleted.
  sed "s|$WORK/||g" "$OUT.tmp"
} > "$OUT"
rm -f "$OUT.tmp"
echo "Wrote $OUT"
